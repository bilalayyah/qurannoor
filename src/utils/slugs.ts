export function toSurahSlug(nameSimple: string): string {
  return nameSimple
    .toLowerCase()
    .replace(/['`’]/g, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
}

export function resolveChapterIdFromParam(
  param: string | undefined,
  chapters: Chapter[]
): number | null {
  if (!param) return null;
  const trimmed = param.trim().toLowerCase();

  // Direct numeric ID
  if (/^\d+$/.test(trimmed)) {
    const id = Number(trimmed);
    return id >= 1 && id <= 114 ? id : null;
  }

  // Exact match against loaded chapters
  const found = chapters.find((ch) => toSurahSlug(ch.name_simple) === trimmed);
  if (found) return found.id;

  // Fallback alias dictionary
  if (SLUG_ALIASES[trimmed]) {
    return SLUG_ALIASES[trimmed];
  }

  return null;
}

